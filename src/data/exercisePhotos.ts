const BASE = '/' // o app é servido na raiz (navegador e Capacitor)

function build(id: string, title: string): ExercisePhotos {
  return { id, title, src: [`${BASE}exercises/${id}/0.jpg`, `${BASE}exercises/${id}/1.jpg`] }
}

export function photosFor(exerciseName: string): ExercisePhotos | null {
  const n = norm(exerciseName)
  if (n in EXACT) {
    const hit = EXACT[n]
    return hit ? build(hit[0], hit[1]) : null
  }
  for (const [re, id, title] of RULES) {
    if (re.test(n)) return build(id, title)
  }
  return null
}